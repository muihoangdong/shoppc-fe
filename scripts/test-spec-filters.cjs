const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const compiled = ts.transpileModule(fs.readFileSync('src/utils/specFilters.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const exportsForTest = {};
new Function('exports', compiled)(exportsForTest);
const { buildSpecFacets, matchesSpecFilters } = exportsForTest;
const templates = [{ id: 1, category_id: 1, fields: [{ key: 'Socket', type: 'select', unit: '', options: ['AM5', 'LGA1700'] }, { key: 'Cores', type: 'number', unit: '' }] }];
const products = [{ category_id: 1, spec_template_id: 1, specs: { Socket: 'AM5', Cores: 8 } }, { category_id: 1, spec_template_id: 1, specs: { Socket: 'LGA1700', Cores: 16 } }, { category_id: 2, specs: { Cores: 8 } }];
const facets = buildSpecFacets(products, templates, 1);
assert.deepEqual(facets[0].options, ['AM5', 'LGA1700']);
assert.equal(facets[1].min, 8); assert.equal(facets[1].max, 16);
assert.deepEqual(buildSpecFacets(products, templates, null), []);
assert(matchesSpecFilters(products[0], { '1:Socket': { values: ['AM5'] }, '1:Cores': { min: 6, max: 8 } }, facets));
assert(!matchesSpecFilters(products[1], { '1:Socket': { values: ['AM5'] } }, facets));
assert(!matchesSpecFilters(products[2], { '1:Cores': { min: 8 } }, facets));
assert(!matchesSpecFilters({ category_id: 1, specs: {} }, { '1:Cores': { min: 0 } }, facets));
assert(!matchesSpecFilters(products[0], { '1:Cores': { min: 16, max: 8 } }, facets));
assert(matchesSpecFilters(products[0], { '1:Cores': {} }, facets));
assert(!matchesSpecFilters({ category_id: 1, specs: { Cores: '8GB' } }, { '1:Cores': { min: 6 } }, facets));
console.log('✓ Lọc thông số: danh mục, nhiều giá trị, khoảng số, thiếu thông số, kiểu số và khoảng đảo');
